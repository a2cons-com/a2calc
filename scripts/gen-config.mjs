#!/usr/bin/env node
// Writes the app identity from config/app.json into the Xcode project
// (bundle ID, version, team), Info.plist (home-screen name) and the Android
// build (android/app/generated.properties, the launcher name), so there is
// one place to change them. Run by every build script; safe to re-run.
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(readFileSync(join(root, 'config/app.json'), 'utf8'));
for (const k of ['appId', 'appName', 'marketingVersion']) {
	if (!cfg[k]) {
		console.error(`config/app.json: "${k}" is required`);
		process.exit(1);
	}
}
if (!/^\d+\.\d+(\.\d+)?$/.test(cfg.marketingVersion)) {
	console.error(`config/app.json: marketingVersion "${cfg.marketingVersion}" must look like 1.2 or 1.2.3`);
	process.exit(1);
}
const team = process.env.DEVELOPMENT_TEAM || cfg.developmentTeam || '';

const pbx = join(root, 'ios/App/App.xcodeproj/project.pbxproj');
let p = readFileSync(pbx, 'utf8');
p = p.replace(/PRODUCT_BUNDLE_IDENTIFIER = [^;]+;/g, `PRODUCT_BUNDLE_IDENTIFIER = ${cfg.appId};`);
p = p.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${cfg.marketingVersion};`);
if (team) {
	if (/DEVELOPMENT_TEAM = /.test(p)) p = p.replace(/DEVELOPMENT_TEAM = [^;]*;/g, `DEVELOPMENT_TEAM = ${team};`);
	else p = p.replace(/(\t+)(CODE_SIGN_STYLE = Automatic;)/g, `$1$2\n$1DEVELOPMENT_TEAM = ${team};`);
}
writeFileSync(pbx, p);

const plistPath = join(root, 'ios/App/App/Info.plist');
let plist = readFileSync(plistPath, 'utf8');
plist = plist.replace(/(<key>CFBundleDisplayName<\/key>\s*<string>)[^<]*(<\/string>)/, `$1${cfg.appName}$2`);
writeFileSync(plistPath, plist);

// Android: identity for Gradle (versionCode = commit count, the same
// number as the iOS build) and the launcher name.
if (existsSync(join(root, 'android/app'))) {
	let versionCode = '1';
	try {
		versionCode = process.env.BUILD_NUMBER || execSync('git rev-list --count HEAD', { cwd: root }).toString().trim() || '1';
	} catch {
		/* not a git checkout */
	}
	writeFileSync(
		join(root, 'android/app/generated.properties'),
		['# GENERATED by scripts/gen-config.mjs from config/app.json; do not edit.', `appId=${cfg.appId}`, `appName=${cfg.appName}`, `versionName=${cfg.marketingVersion}`, `versionCode=${versionCode}`, ''].join('\n')
	);
	const strings = join(root, 'android/app/src/main/res/values/strings.xml');
	let x = readFileSync(strings, 'utf8');
	x = x.replace(/(<string name="app_name">)[^<]*(<\/string>)/, `$1${cfg.appName}$2`).replace(/(<string name="title_activity_main">)[^<]*(<\/string>)/, `$1${cfg.appName}$2`);
	writeFileSync(strings, x);
	console.log(`android project: ${cfg.appId} "${cfg.appName}" v${cfg.marketingVersion} (${versionCode})`);
}

// macOS: the xcconfig the generated Xcode project (macos/project.yml) reads.
if (existsSync(join(root, 'macos/project.yml'))) {
	let build = '1';
	try {
		build = process.env.BUILD_NUMBER || execSync('git rev-list --count HEAD', { cwd: root }).toString().trim() || '1';
	} catch {
		/* not a git checkout */
	}
	writeFileSync(
		join(root, 'macos/Config.generated.xcconfig'),
		[
			'// GENERATED by scripts/gen-config.mjs from config/app.json; do not edit.',
			`PRODUCT_BUNDLE_IDENTIFIER = ${cfg.appId}`,
			`APP_DISPLAY_NAME = ${cfg.appName}`,
			`MARKETING_VERSION = ${cfg.marketingVersion}`,
			`CURRENT_PROJECT_VERSION = ${build}`,
			`DEVELOPMENT_TEAM = ${team}`,
			'MACOSX_DEPLOYMENT_TARGET = 13.0',
			''
		].join('\n')
	);
	console.log(`macos project: ${cfg.appId} "${cfg.appName}" v${cfg.marketingVersion} (${build})`);
}

console.log(`ios project: ${cfg.appId} "${cfg.appName}" v${cfg.marketingVersion}${team ? `, team ${team}` : ''}`);

// Third-party licenses for the About screen.
await import('./gen-licenses.mjs');
